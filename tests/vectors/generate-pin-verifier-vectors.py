"""PIN verifier vectors (ADR-0028 §4), computed with Python's hashlib/hmac: an implementation independent of both the
browser (@karry/crypto) and the server (Identity), which must each reproduce them.

verifier = HMAC-SHA256(pinKey, PBKDF2-SHA256(pin, salt, iterations, 32 bytes)); "stored" is the server's PIN hash.
Run: python3 tests/vectors/generate-pin-verifier-vectors.py > tests/vectors/pin-verifier.json
"""
import base64
import hashlib
import hmac
import json

CASES = [
    ("583920", bytes(range(16)), 1_000, bytes(range(32, 64))),
    ("402817", bytes.fromhex("9f1c2e7a55b0d3416c88e2f0a1b4c7d9"), 600_000, bytes.fromhex("00" * 31 + "ff")),
    ("090909", b"\xff" * 16, 10_000, b"\x01" * 32),
]

vectors = []
for pin, salt, iterations, pin_key in CASES:
    derived = hashlib.pbkdf2_hmac("sha256", pin.encode(), salt, iterations, 32)
    b64 = lambda raw: base64.b64encode(raw).decode()
    vectors.append({
        "pin": pin,
        "salt": b64(salt),
        "iterations": iterations,
        "pinKey": b64(pin_key),
        "stored": f"pbkdf2-sha256${iterations}${b64(salt)}${b64(derived)}",
        "verifier": b64(hmac.new(pin_key, derived, hashlib.sha256).digest()),
    })

print(json.dumps({"description": "PIN verifier vectors (ADR-0028 §4) generated by tests/vectors/generate-pin-verifier-vectors.py", "vectors": vectors}, indent=1))
