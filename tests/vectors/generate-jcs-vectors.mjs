// Generates tests/vectors/rfc8785.json: RFC 8785 (JCS) vectors produced by a real ECMAScript engine (Node.js), so the
// .NET canonicalizer (and later the TypeScript one in packages/crypto) is checked against the reference semantics:
// JSON.stringify for strings and numbers, UTF-16 code-unit ordering for object keys.
// Run: node tests/vectors/generate-jcs-vectors.mjs   (deterministic: fixed seed)
import { writeFileSync } from "node:fs";

const canonicalize = (v) =>
  v === null || typeof v !== "object"
    ? JSON.stringify(v)
    : Array.isArray(v)
      ? `[${v.map(canonicalize).join(",")}]`
      : `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canonicalize(v[k])}`).join(",")}}`;

// RFC 8785 Appendix B: IEEE-754 bit patterns and their expected serialization (computed here, not copied).
const bits = [
  "0000000000000000", "8000000000000000", "0000000000000001", "8000000000000001", "7fefffffffffffff",
  "ffefffffffffffff", "4340000000000000", "c340000000000000", "4430000000000000", "44b52d02c7e14af5",
  "44b52d02c7e14af6", "44b52d02c7e14af7", "444b1ae4d6e2ef4e", "444b1ae4d6e2ef4f", "444b1ae4d6e2ef50",
  "3eb0c6f7a0b5ed8c", "3eb0c6f7a0b5ed8d", "41b3de4355555553", "41b3de4355555554", "41b3de4355555555",
  "41b3de4355555556", "41b3de4355555557", "becbf647612f3696", "43143ff3c1cb0959",
];
const view = new DataView(new ArrayBuffer(8));
const numbers = bits.map((hex) => {
  view.setBigUint64(0, BigInt(`0x${hex}`));
  const value = view.getFloat64(0);
  return { bits: hex, expected: JSON.stringify(value) === "null" ? null : canonicalize(value) };
});

// Deterministic random documents: nested objects/arrays, unicode keys (incl. astral), control characters, numbers.
let seed = 0x5eed1234;
const random = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 2 ** 32);
const pick = (items) => items[Math.floor(random() * items.length)];
const chars = ["a", "Z", "0", " ", "é", "€", "ö", "\u0080", "\u001f", "\n", "\t", '"', "\\", "/", "😀", "דּ", "\r", " "];
const str = () => Array.from({ length: Math.floor(random() * 6) }, () => pick(chars)).join("");
const num = () => pick([0, -0, 1, -1, 4.5, 0.002, 1e30, 1e-27, 1e21, 1e-7, 123456789, 2 ** 53, 333333333.3333333, Math.floor(random() * 1e6) / 100]);
const value = (depth) => {
  const kind = depth > 3 ? pick(["s", "n", "b", "z"]) : pick(["s", "n", "b", "z", "o", "o", "a"]);
  if (kind === "s") return str();
  if (kind === "n") return num();
  if (kind === "b") return random() < 0.5;
  if (kind === "z") return null;
  if (kind === "a") return Array.from({ length: Math.floor(random() * 4) }, () => value(depth + 1));
  const o = {};
  for (let i = Math.floor(random() * 5); i > 0; i--) o[str()] = value(depth + 1);
  return o;
};
const documents = Array.from({ length: 300 }, () => {
  const v = value(0);
  // The input is written with JSON.stringify (insertion order, ECMAScript formatting) and a few spaces.
  return { input: JSON.stringify(v, null, random() < 0.5 ? 0 : 1), expected: canonicalize(v) };
});

const rfcExample = {
  input: '{\n  "numbers": [333333333.33333329, 1E30, 4.50, 2e-3, 0.000000000000000000000000001],\n  "string": "\\u20ac$\\u000F\\u000aA\'\\u0042\\u0022\\u005c\\\\\\"\\/",\n  "literals": [null, true, false]\n}',
  expected: canonicalize(JSON.parse('{\n  "numbers": [333333333.33333329, 1E30, 4.50, 2e-3, 0.000000000000000000000000001],\n  "string": "\\u20ac$\\u000F\\u000aA\'\\u0042\\u0022\\u005c\\\\\\"\\/",\n  "literals": [null, true, false]\n}')),
};
const sortingExample = {
  input: '{"\\u20ac":"Euro Sign","\\r":"Carriage Return","\\ufb33":"Hebrew Letter Dalet With Dagesh","1":"One","\\ud83d\\ude00":"Emoji: Grinning Face","\\u0080":"Control","\\u00f6":"Latin Small Letter O With Diaeresis"}',
};
sortingExample.expected = canonicalize(JSON.parse(sortingExample.input));

writeFileSync(new URL("./rfc8785.json", import.meta.url), JSON.stringify({
  description: "RFC 8785 JCS vectors generated by tests/vectors/generate-jcs-vectors.mjs with Node.js " + process.version,
  examples: [rfcExample, sortingExample],
  numbers,
  documents,
}, null, 1) + "\n");
console.log(`wrote ${numbers.length} numbers, ${documents.length} documents`);
